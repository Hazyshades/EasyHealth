function corpusSafety(row: CandidateCorpusReportRow): string {
  if (row.actualClassification === "resolved") return row.classificationMatches ? "Safe concrete resolution: reviewed expected definition selected." : "Unsafe classification mismatch.";
  if (row.actualClassification === "partial") return row.classificationMatches ? "Safe incomplete outcome: an identity axis remains insufficient." : "Incomplete outcome differs from expectation.";
  if (row.actualClassification === "ambiguous") return row.classificationMatches ? "Safe non-concrete outcome: candidates remain unresolved." : "Ambiguity differs from expectation.";
  if (row.actualClassification === "unmapped") return row.classificationMatches ? "Safe unmapped outcome: raw evidence remains and catalog does not grow." : "Unmapped outcome differs from expectation.";
  return "Processing error requires investigation.";
}

function renderCorpus(report: CandidateCorpusReport): string {
  const segments = sortBy(Object.entries(report.segments.language), ([locale]) => locale)
    .map(([locale, segment]) => `| ${locale} | ${segment.total} | ${segment.resolved} | ${segment.partial} | ${segment.ambiguous} | ${segment.unmapped} | ${segment.expectedClassificationFailures} | ${segment.falseConcreteResolutions} | ${segment.processingErrors} |`);
  const rows = sortBy(report.rows, (row) => row.id).map((row) => {
    const expected = `${row.expectedClassification}${row.expectedMeasurementDefinitionKey ? ` / ${row.expectedMeasurementDefinitionKey}` : ""}`;
    const actual = `${row.actualClassification ?? "error"}${row.actualMeasurementDefinitionKey ? ` / ${row.actualMeasurementDefinitionKey}` : ""}`;
    const aliasEvidence = row.aliasMatchTypes.length === 0 ? "—" : row.aliasMatchTypes.join(", ");
    return `| ${escapeMarkdownCell(row.id)} | ${escapeMarkdownCell(row.language)} | ${escapeMarkdownCell(row.rawEvidence.label)} | ${escapeMarkdownCell(`${row.rawEvidence.unit ?? "no unit"} / ${row.rawEvidence.valueText}`)} | ${escapeMarkdownCell(expected)} | ${escapeMarkdownCell(actual)} | ${row.falseConcreteResolution ? "yes" : "no"} | ${escapeMarkdownCell(aliasEvidence)} | ${escapeMarkdownCell(corpusSafety(row))} |`;
  });
  return [
    GENERATED_NOTICE,
    "# Registry 2.0 Biomarker Corpus Evidence",
    "",
    "Technical resolver evidence only. This document is independent from the release-governance record.",
    "",
    `- **Rows:** ${report.rows.length}; **expected classification rate:** ${report.metrics.expectedClassificationRate}; **false concrete resolutions:** ${report.metrics.falseConcreteResolutions}; **processing errors:** ${report.metrics.processingErrors}.`,
    "",
    "## Language segments",
    "",
    "| language | total | resolved | partial | ambiguous | unmapped | expected failures | false-concrete | processing errors |",
    "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ...segments,
    "",
    "## Row evidence",
    "",
    "Unknown-marker rows remain `unmapped`; uploads never silently create definitions or aliases.",
    "",
    "| row | language | raw label | unit / value | expected | actual | false-concrete | alias evidence | safety rationale |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}


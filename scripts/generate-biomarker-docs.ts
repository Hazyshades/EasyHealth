export function buildBiomarkerDocumentation(root = ROOT): BiomarkerDocumentation {
  const definitions = sortBy(MEASUREMENT_DEFINITIONS, (definition) => definition.key);
  const counts = getBiomarkerDocumentationCounts(definitions);
  const baseline = readBaseline(root);
  const technical = runRegistryV2CandidateCorpusTechnical({ root: resolve(root, DEFAULT_CANDIDATE_CORPUS_ROOT) });
  validateBiomarkerDocumentationInputs(definitions, counts, baseline, technical);
  const files: BiomarkerDocumentationOutput = {
    module: renderModule(counts),
    catalog: renderCatalog(definitions, counts),
    aliases: renderAliases(definitions, counts),
    corpus: renderCorpus(technical.report),
  };
  return { files, readmeSection: renderReadmeSection(counts), issueBody: renderIssueBody(counts, technical.report) };
}

export function replaceReadmeSection(content: string, section: string): string {
  const starts = [...content.matchAll(/<!-- generated-biomarker-docs:start -->/g)];
  const ends = [...content.matchAll(/<!-- generated-biomarker-docs:end -->/g)];
  if (starts.length !== 1 || ends.length !== 1 || starts[0]!.index! >= ends[0]!.index!) {
    throw new Error("docs/README.md must contain exactly one correctly ordered generated biomarker marker pair");
  }
  const before = content.slice(0, starts[0]!.index! + README_START.length);
  const after = content.slice(ends[0]!.index!);
  return `${before}\n${section}\n${after}`;
}

export function staleBiomarkerDocumentationFiles(root = ROOT, documentation = buildBiomarkerDocumentation(root)): string[] {
  const stale = (Object.entries(BIOMARKER_DOCUMENT_PATHS) as Array<[DocumentKey, string]>)
    .filter(([key, path]) => {
      try {
        return readFileSync(resolve(root, path), "utf8") !== documentation.files[key];
      } catch {
        return true;
      }
    })
    .map(([, path]) => path);
  try {
    const readme = readFileSync(resolve(root, "docs/README.md"), "utf8");
    if (replaceReadmeSection(readme, documentation.readmeSection) !== readme) stale.push("docs/README.md (managed biomarker section)");
  } catch {
    stale.push("docs/README.md (managed biomarker section)");
  }
  return stale;
}

export function writeBiomarkerDocumentation(root = ROOT, documentation = buildBiomarkerDocumentation(root)): void {
  const readmePath = resolve(root, "docs/README.md");
  const nextReadme = replaceReadmeSection(readFileSync(readmePath, "utf8"), documentation.readmeSection);
  for (const [key, relativePath] of Object.entries(BIOMARKER_DOCUMENT_PATHS) as Array<[DocumentKey, string]>) {
    const path = resolve(root, relativePath);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, documentation.files[key], "utf8");
  }
  writeFileSync(readmePath, nextReadme, "utf8");
}

function main(): void {
  const [mode] = process.argv.slice(2);
  if (!mode || !["--write", "--check", "--issue-body"].includes(mode) || process.argv.length > 3) {
    throw new Error("Usage: tsx scripts/generate-biomarker-docs.ts --write|--check|--issue-body");
  }
  const documentation = buildBiomarkerDocumentation();
  if (mode === "--issue-body") {
    process.stdout.write(documentation.issueBody);
    return;
  }
  if (mode === "--check") {
    const stale = staleBiomarkerDocumentationFiles(ROOT, documentation);
    if (stale.length > 0) throw new Error(`Biomarker documentation is stale:\n${stale.map((path) => `- ${path}`).join("\n")}`);
    console.log("check:biomarker-docs: generated files are current");
    return;
  }
  writeBiomarkerDocumentation(ROOT, documentation);
  console.log(`generate:biomarker-docs: wrote ${Object.keys(BIOMARKER_DOCUMENT_PATHS).length} files and the README managed section`);
}

if (process.argv[1]?.replace(/\\/g, "/").endsWith("/scripts/generate-biomarker-docs.ts")) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}

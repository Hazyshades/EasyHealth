function compareStable(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function sortBy<T>(values: readonly T[], key: (value: T) => string): T[] {
  return [...values].sort((left, right) => compareStable(key(left), key(right)));
}

export function escapeMarkdownCell(value: unknown): string {
  if (value === null || value === undefined || value === "") return "—";
  return String(value)
    .replace(/\\/g, "\\\\")
    .replace(/\|/g, "\\|")
    .replace(/\r?\n/g, "<br>");
}

function code(value: unknown): string {
  return `\`${escapeMarkdownCell(value)}\``;
}

function list(values: readonly unknown[], empty = "—"): string {
  return values.length > 0 ? values.map(escapeMarkdownCell).join(", ") : empty;
}

function contributionGroups(values: readonly { id: string; keys: readonly string[] }[]): string {
  return values.length > 0
    ? values.map((group) => `${code(group.id)}: ${list(group.keys.map(code))}`).join("; ")
    : "—";
}

function readBaseline(root = ROOT): DocumentationBaseline {
  const baseline = JSON.parse(readFileSync(resolve(root, BASELINE_PATH), "utf8")) as DocumentationBaseline;
  if (baseline.schemaVersion !== "1") throw new Error("Documentation baseline has an unsupported schema version");
  return baseline;
}

export function getBiomarkerDocumentationCounts(
  definitions: readonly MeasurementDefinition[] = MEASUREMENT_DEFINITIONS,
  analyteCount = ANALYTES.length,
): BiomarkerDocumentationCounts {
  const aliases = definitions.flatMap((definition) => definition.aliases);
  const aliasesByLocale: Record<string, number> = {};
  for (const alias of aliases) {
    const locale = alias.locale ?? "unknown";
    aliasesByLocale[locale] = (aliasesByLocale[locale] ?? 0) + 1;
  }
  return {
    definitions: definitions.length,
    reviewedDefinitions: definitions.filter((definition) => definition.maturity === "reviewed").length,
    provisionalDefinitions: definitions.filter((definition) => definition.maturity === "provisional").length,
    retiredDefinitions: definitions.filter((definition) => definition.maturity === "retired").length,
    analytes: analyteCount,
    aliases: aliases.length,
    assessmentBoundDefinitions: definitions.filter((definition) => definition.assessmentBindings.length > 0).length,
    aliasesByLocale,
  };
}

function sameCounts(actual: BiomarkerDocumentationCounts, expected: BiomarkerDocumentationCounts): string[] {
  const failures: string[] = [];
  for (const key of ["definitions", "reviewedDefinitions", "provisionalDefinitions", "retiredDefinitions", "analytes", "aliases", "assessmentBoundDefinitions"] as const) {
    if (actual[key] !== expected[key]) failures.push(`${key}=${actual[key]} (baseline ${expected[key]})`);
  }
  for (const locale of LOCALES) {
    if ((actual.aliasesByLocale[locale] ?? 0) !== (expected.aliasesByLocale[locale] ?? 0)) {
      failures.push(`aliases.${locale}=${actual.aliasesByLocale[locale] ?? 0} (baseline ${expected.aliasesByLocale[locale] ?? 0})`);
    }
  }
  return failures;
}

export function validateBiomarkerDocumentationDefinitions(definitions: readonly MeasurementDefinition[]): string[] {
  const errors = [...validateMeasurementRegistry(definitions).errors];
  const definitionKeys = new Set<string>();
  const aliasKeys = new Set<string>();
  for (const definition of definitions) {
    if (definitionKeys.has(definition.key)) errors.push(`Duplicate measurement definition key: ${definition.key}`);
    definitionKeys.add(definition.key);
    for (const alias of definition.aliases) {
      if (aliasKeys.has(alias.key)) errors.push(`Duplicate alias key: ${alias.key}`);
      aliasKeys.add(alias.key);
      if (alias.measurementDefinitionKey !== definition.key) {
        errors.push(`Alias ${alias.key} has mismatched owner ${alias.measurementDefinitionKey}`);
      }
      if (!alias.locale || !LOCALES.includes(alias.locale as (typeof LOCALES)[number])) {
        errors.push(`Alias ${alias.key} has an unsupported locale`);
      }
      if (!alias.provenance?.kind || !alias.provenance.sourceRecordKey || !alias.matchAuthority || !alias.approvalStatus || !alias.lifecycle) {
        errors.push(`Alias ${alias.key} is missing governance metadata`);
      }
    }
    for (const binding of definition.assessmentBindings) {
      if (binding.status === "reviewed" && binding.compatibility === "compatible" && (
        !binding.assessmentInputKey || !binding.system || !binding.scoreRole || binding.coversConfidence === undefined
      )) {
        errors.push(`Reviewed compatible assessment binding is missing runtime metadata: ${definition.key}`);
      }
    }
  }
  return [...new Set(errors)].sort(compareStable);
}

export function validateBiomarkerDocumentationInputs(
  definitions: readonly MeasurementDefinition[],
  counts: BiomarkerDocumentationCounts,
  baseline: DocumentationBaseline,
  technical: CandidateCorpusTechnicalRun,
): void {
  const errors = validateBiomarkerDocumentationDefinitions(definitions);
  if (baseline.catalog.manifestVersion !== MEASUREMENT_CATALOG_MANIFEST_VERSION) {
    errors.push(`Baseline manifest version ${baseline.catalog.manifestVersion} does not match runtime ${MEASUREMENT_CATALOG_MANIFEST_VERSION}`);
  }
  if (baseline.catalog.manifestDigest !== MEASUREMENT_CATALOG_MANIFEST_DIGEST) {
    errors.push(`Baseline manifest digest ${baseline.catalog.manifestDigest} does not match runtime ${MEASUREMENT_CATALOG_MANIFEST_DIGEST}`);
  }
  errors.push(...sameCounts(counts, baseline.catalog.counts));
  if (technical.report.rows.length !== baseline.technicalCorpus.rows) {
    errors.push(`technical corpus rows=${technical.report.rows.length} (baseline ${baseline.technicalCorpus.rows})`);
  }
  for (const locale of LOCALES) {
    const actual = technical.report.segments.language[locale]?.total ?? 0;
    const expected = baseline.technicalCorpus.rowsByLocale[locale] ?? 0;
    if (actual !== expected) errors.push(`technical corpus ${locale}=${actual} (baseline ${expected})`);
  }
  if (technical.manifest.fixtureErrors.length > 0) errors.push(...technical.manifest.fixtureErrors);
  for (const check of technical.manifest.thresholdChecks) if (!check.passed) errors.push(`technical corpus threshold failed: ${check.metric}`);
  if (errors.length > 0) throw new Error(`Cannot generate biomarker documentation:\n${errors.map((error) => `- ${error}`).join("\n")}`);
}

function aliasGroups(definition: MeasurementDefinition): Map<string, AliasDefinition[]> {
  const groups = new Map<string, AliasDefinition[]>();
  for (const locale of LOCALES) groups.set(locale, []);
  for (const alias of definition.aliases) groups.get(alias.locale ?? "unknown")?.push(alias);
  for (const aliases of groups.values()) aliases.sort((left, right) => compareStable(left.key, right.key));
  return groups;
}

function formatConversion(definition: MeasurementDefinition): string {
  const conversion = getMeasurementConversionPolicy(definition.key);
  if (!conversion) return "none (no reviewed conversion rule)";
  if (conversion.type === "linear") return `linear: ${conversion.conventionalUnit} → ${conversion.siUnit} × ${conversion.factorCo}; ${conversion.siUnit} → ${conversion.conventionalUnit} × ${conversion.factorSi}`;
  if (conversion.type === "equal") return `equal: ${conversion.conventionalUnit} = ${conversion.siUnit}`;
  if (conversion.type === "formula") return `formula ${code(conversion.formula)}: ${conversion.conventionalUnit} ↔ ${conversion.siUnit}`;
  return `none: ${conversion.reason}`;
}

function projectEligibility(definition: MeasurementDefinition) {
  const relation: RegistryV2NormalizationRevisionReadBoundary = {
    resolver_result: "resolved",
    verification_status: "user_verified",
    measurement_definition_key: definition.key,
    is_active: true,
    resolver_evidence: { version: 2, selectedCandidateKey: definition.key, outcome: "resolved" },
  };
  const observation = {
    observation_kind: "lab" as const,
    measurement_definition_key: definition.key,
    resolution_status: "resolved",
    name: definition.displayName,
    value: 1,
    unit: definition.unitPolicy.canonicalUnit ?? "",
    ref_low: 0,
    ref_high: 2,
    raw_reference_text: "0–2",
    observed_at: "2000-01-01",
    document_id: "documentation-fixture",
    value_kind: "numeric",
    value_text: "1",
    ordinal: null,
    specimen: definition.specimen,
    modifier: definition.timing,
  };
  const binding = projectActiveRegistryV2LaboratoryBinding(observation, relation);
  const outcome = projectLaboratoryOutcome({ observation, relation });
  const input = projectHealthProfileLaboratoryInput({ observation, relation, labUnitSystem: "si" });
  const reviewedBinding = getReviewedAssessmentBinding(definition.key);
  const system = reviewedBinding?.binding.system ?? "general";
  return {
    eligible: input !== null,
    binding,
    outcome,
    reviewedBinding,
    scoreRole: getRegistryV2ScoreRole(definition.key),
    readinessGroups: getRegistryV2ScoreReadinessGroups(system),
    contributionGroups: getRegistryV2ScoreContributionGroups(system),
    reviewedReadinessGroups: getReviewedScoreReadinessGroups(system),
    reviewedContributionGroups: getReviewedScoreContributionGroups(system),
  };
}

function renderAliasesByLocale(definition: MeasurementDefinition): string {
  const groups = aliasGroups(definition);
  return LOCALES.map((locale) => {
    const aliases = groups.get(locale) ?? [];
    const rendered = aliases.length === 0 ? "—" : aliases.map((alias) => `${escapeMarkdownCell(alias.value)} [${code(alias.key)}${alias.laboratory ? `; laboratory=${code(alias.laboratory)}` : ""}]`).join(" · ");
    return `- **${locale}** (${aliases.length}): ${rendered}`;
  }).join("\n");
}

function renderDefinition(definition: MeasurementDefinition): string {
  const [analyteKey, specimen, property, scale, timing, method, valueKind] = getMeasurementIdentity(definition);
  const projection = projectEligibility(definition);
  const definitionBinding = projection.reviewedBinding?.binding;
  return [
    `### ${code(definition.key)} — ${escapeMarkdownCell(definition.displayName)}`,
    "",
    `- **analyte:** ${code(analyteKey)}`,
    `- **specimen / property / scale:** ${code(specimen)} / ${code(property)} / ${code(scale)}`,
    `- **timing / method / value kind:** ${code(timing)} / ${code(method)} / ${code(valueKind)}`,
    `- **maturity:** ${code(definition.maturity)}; **definition provenance:** ${code(definition.sourceProvenance.kind)} / ${code(definition.sourceProvenance.sourceRecordKey)}`,
    `- **concrete-resolution eligibility:** ${definition.maturity === "reviewed" ? "reviewed identity may resolve only after authorized label and clinical-axis compatibility" : "recognition-only; cannot select a concrete identity"}`,
    `- **unit dimensions:** ${list(definition.unitPolicy.dimensions.map(code))}; **accepted units:** ${list(definition.unitPolicy.acceptedUnits.map(code))}; **canonical unit:** ${code(definition.unitPolicy.canonicalUnit)}`,
    `- **conversion policy:** ${code(definition.unitPolicy.conversionPolicyRef)}; **missing-unit behavior:** ${code(definition.unitPolicy.missingUnitPolicy)}; **conversion:** ${formatConversion(definition)}`,
    `- **required modifiers / methods:** ${list((definition.requiredModifiers ?? []).map(code))} / ${list((definition.requiredMethods ?? []).map(code))}`,
    `- **Health Profile consumer eligibility:** ${projection.eligible ? "yes" : "no"}. It requires a lab observation, active \`resolved\` revision/trace, matching selected candidate and definition key, reviewed Registry v2 provenance, and a reviewed compatible assessment binding.`,
    `- **reviewed binding:** ${definitionBinding ? `${code(definitionBinding.assessmentInputKey)}; system=${code(definitionBinding.system)}; compatibility=${code(definitionBinding.compatibility)}; status=${code(definitionBinding.status)}` : "—"}`,
    `- **score role / readiness / contribution groups:** ${code(projection.scoreRole)} / ${list(projection.readinessGroups.map(code))} / ${contributionGroups(projection.contributionGroups)}`,
    `- **reviewed groups:** readiness ${list(projection.reviewedReadinessGroups.map(code))}; contribution ${contributionGroups(projection.reviewedContributionGroups)}`,
    "",
    "**Compact aliases by locale**",
    renderAliasesByLocale(definition),
    "",
  ].join("\n");
}

